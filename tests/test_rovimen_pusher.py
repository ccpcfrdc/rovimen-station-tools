class TestSpool:
    def test_add_and_pending(self, tmp_path):
        sp = rp.Spool(path=tmp_path / "spool.db")
        sp.add("detections", "detections", {"seq": 1})
        pending = sp.pending()
        assert len(pending) == 1
        _, endpoint, body = pending[0]
        assert endpoint == "detections"
        assert body == {"seq": 1}
        sp.close()

    def test_heartbeat_coalesces_to_latest(self, tmp_path):
        sp = rp.Spool(path=tmp_path / "spool.db")
        sp.add("heartbeat", "heartbeat", {"seq": 1})
        sp.add("heartbeat", "heartbeat", {"seq": 2})
        sp.add("heartbeat", "heartbeat", {"seq": 3})
        pending = sp.pending()
        assert len(pending) == 1
        assert pending[0][2] == {"seq": 3}
        sp.close()

    def test_detections_do_not_coalesce(self, tmp_path):
        sp = rp.Spool(path=tmp_path / "spool.db")
        sp.add("detections", "detections", {"seq": 1})
        sp.add("detections", "detections", {"seq": 2})
        assert sp.count() == 2
        sp.close()

    def test_remove(self, tmp_path):
        sp = rp.Spool(path=tmp_path / "spool.db")
        sp.add("vitals", "vitals", {"seq": 1})
        row_id = sp.pending()[0][0]
        sp.remove(row_id)
        assert sp.count() == 0
        sp.close()

    def test_bounded_size(self, tmp_path, monkeypatch):
        monkeypatch.setattr(rp, "SPOOL_MAX_ROWS", 5)
        sp = rp.Spool(path=tmp_path / "spool.db")
        for i in range(20):
            sp.add("detections", "detections", {"seq": i})
        assert sp.count() == 5
        # kept the newest
        seqs = sorted(b["seq"] for _, _, b in sp.pending())
        assert seqs == [15, 16, 17, 18, 19]
        sp.close()


